import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { watchMessages, watchCaptions } from '../src/ui/messages/watch.ts';

const args = process.argv.slice(2);
assert(args.length === 0 || (args.length === 1 && args[0] === '--check'), 'Use --check or no arguments.');
const check = args[0] === '--check';
const escape = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
const template = await readFile(new URL('./watch-page.html', import.meta.url), 'utf8');
const page = template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
  assert(Object.hasOwn(watchMessages, key), `Unknown watch message: ${key}`);
  return escape(watchMessages[key]);
});
assert(!page.includes('{{'), 'Unresolved watch page message.');
const generated = '<!-- Generated by scripts/export-watch-page.mjs; edit src/ui/messages/watch.ts. -->\n';
const outputs = new Map([['public/watch/index.html', page.replace('<html lang=', generated + '<html lang=')]]);
function seconds(value) {
  assert(/^\d{2}:\d{2}:\d{2}\.\d{3}$/.test(value), 'Use WebVTT timestamps.');
  const [h, m, s] = value.split(':').map(Number);
  assert(m < 60 && s < 60, 'Invalid WebVTT timestamp.');
  return h * 3600 + m * 60 + s;
}
for (const [name, cues] of Object.entries(watchCaptions)) {
  let end = 0;
  const ids = new Set();
  const body = cues.map(cue => {
    assert(!ids.has(cue.id) && cue.text.trim(), 'Caption IDs must be unique and text nonempty.');
    ids.add(cue.id);
    assert(seconds(cue.start) === end && seconds(cue.end) > end, 'Captions must cover the film continuously.');
    end = seconds(cue.end);
    return `${cue.id}\n${cue.start} --> ${cue.end}\n${cue.text}`;
  }).join('\n\n');
  outputs.set(`public/media/${name}.vtt`, `WEBVTT\n\n${body}\n`);
}
for (const [file, content] of outputs) {
  const url = new URL('../' + file, import.meta.url);
  if (check) {
    assert.equal(await readFile(url, 'utf8'), content, `${file} differs from its message source; run npm run demos:export.`);
  } else await writeFile(url, content);
}
console.log(check ? 'Demo page and captions match their message modules.' : 'Exported demo page and captions.');
